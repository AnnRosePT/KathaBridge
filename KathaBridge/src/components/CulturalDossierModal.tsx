import React, { useState } from "react";
import { Story } from "../types";
import { mockSources } from "../data/mockData";
import { Soundtrack } from "../services/soundtrackService";

interface CulturalDossierModalProps {
  story: Story;
  onClose: () => void;
}

export const CulturalDossierModal: React.FC<CulturalDossierModalProps> = ({ story, onClose }) => {
  const [copied, setCopied] = useState(false);
  const resolvedSource = mockSources.find((s) => s.id === story.sourceId);

  const accessionNumber = `KB-KL-2026-${story.id.toUpperCase().slice(0, 6)}`;
  const currentDate = new Date().toISOString().split("T")[0];

  const handlePrint = () => {
    Soundtrack.playClick();
    window.print();
  };

  const generateMarkdownReport = () => {
    return `# KATHABRIDGE DIGITAL FOLKLORE ARCHIVE
## Anthro-Cultural Monograph & Provenance Dossier

**Accession ID**: ${accessionNumber}
**Date of Record**: ${currentDate}
**Primary Subject**: ${story.title} (${story.malayalamTitle})
**Region/District**: Kerala, South India
**UNESCO Classification**: ${story.unescoDomain || "Oral Traditions & Intangible Cultural Heritage"}
**Verified Scholar**: ${story.scholarVerifier || "Dr. Ananya Nair (Kerala Folklore Society)"}

---

### 1. CULTURAL KEY CONCEPT
> "${story.keyConcept.quote}"
*${story.keyConcept.title}*: ${story.keyConcept.explanation}

---

### 2. SYNCHRONIZED ORAL NARRATIVE (${story.sentences.length} Verses)
${story.sentences
  .map(
    (s, idx) => `**Verse ${idx + 1}**:
- English: ${s.en}
- Malayalam: ${s.ml}
- Phonetic Transliteration: ${s.transliteration}`
  )
  .join("\n\n")}

---

### 3. ACADEMIC CITATION & PROVENANCE
- Source: ${resolvedSource?.title || "Kerala Folklore Digital Archive"}
- Institution: ${resolvedSource?.institution || "Kerala Kalamandalam / Sahapedia"}
- License: ${story.license || "Creative Commons Attribution-NonCommercial (CC BY-NC 4.0)"}
- Permanent Canonical URI: https://kathabridge.vercel.app/story/${story.id}

---
*Generated by KathaBridge Digital Oral Heritage Engine (Open Access & Preservation)*
`;
  };

  const handleCopyMarkdown = () => {
    Soundtrack.playSuccessChime();
    navigator.clipboard.writeText(generateMarkdownReport());
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <div
      role="dialog"
      aria-modal="true"
      aria-labelledby="dossier-title"
      className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-6 bg-black/85 backdrop-blur-sm print:bg-white print:p-0 print:static"
    >
      <div className="bg-[#FFFDE0] border-4 border-brandBlack rounded-2xl max-w-3xl w-full max-h-[90vh] flex flex-col shadow-[8px_8px_0px_#080808] print:shadow-none print:border-none print:max-h-none print:w-full">
        {/* Header Bar - Hidden in print */}
        <div className="flex items-center justify-between p-4 bg-brandYellow border-b-4 border-brandBlack rounded-t-xl print:hidden">
          <div className="flex items-center gap-2">
            <span className="text-xl">🖨️</span>
            <div>
              <h2 id="dossier-title" className="font-mono text-sm sm:text-base font-black text-brandBlack uppercase tracking-wide">
                Cultural Archival Dossier
              </h2>
              <span className="font-mono text-[11px] text-brandBlack/80 font-bold">
                Accession: {accessionNumber} • Peer-Reviewed Record
              </span>
            </div>
          </div>
          <button
            onClick={() => {
              Soundtrack.playModalPop();
              onClose();
            }}
            className="w-8 h-8 rounded-full border-2 border-brandBlack bg-white hover:bg-brandPink hover:text-white flex items-center justify-center font-bold text-sm transition cursor-pointer shadow-[2px_2px_0px_#080808]"
            aria-label="Close dossier modal"
          >
            ✕
          </button>
        </div>

        {/* Scrollable Printable Monograph Body */}
        <div className="p-6 overflow-y-auto font-sans text-brandBlack space-y-6 print:p-8 print:text-black">
          {/* Institutional Header Stamp */}
          <div className="border-b-2 border-brandBlack pb-4 flex flex-col sm:flex-row justify-between items-start sm:items-end gap-3">
            <div>
              <span className="font-mono text-[10px] uppercase font-black tracking-widest text-brandPink print:text-black">
                KATHABRIDGE DIGITAL HERITAGE ARCHIVE • MONOGRAPH SERIES
              </span>
              <h1 className="text-2xl sm:text-3xl font-black mt-1">
                {story.title}
              </h1>
              <p className="font-serif text-lg text-brandPink font-bold print:text-black">
                {story.malayalamTitle}
              </p>
            </div>
            <div className="text-right sm:text-right font-mono text-xs font-bold border-2 border-brandBlack px-3 py-1.5 rounded-lg bg-white shadow-[2px_2px_0px_#080808] print:shadow-none">
              <div>Record: <span className="font-black">{accessionNumber}</span></div>
              <div className="text-[11px] text-emerald-700 font-black">STATUS: VERIFIED SCHOLAR</div>
            </div>
          </div>

          {/* Metadata Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 bg-white border-2 border-brandBlack p-3 rounded-xl font-mono text-xs print:border-gray-400">
            <div>
              <span className="text-neutral-500 block text-[10px] font-bold">DOMAIN</span>
              <span className="font-black text-brandBlack">{story.unescoDomain || "Oral Folklore"}</span>
            </div>
            <div>
              <span className="text-neutral-500 block text-[10px] font-bold">SCHOLAR COUNCIL</span>
              <span className="font-black text-brandBlack">{story.scholarVerifier || "Dr. Ananya Nair"}</span>
            </div>
            <div>
              <span className="text-neutral-500 block text-[10px] font-bold">LICENSE</span>
              <span className="font-black text-brandBlack">CC BY-NC 4.0</span>
            </div>
            <div>
              <span className="text-neutral-500 block text-[10px] font-bold">VERSES RECORDED</span>
              <span className="font-black text-brandBlack">{story.sentences.length} Units</span>
            </div>
          </div>

          {/* Key Hermeneutic Concept */}
          <div className="bg-brandYellow/30 border-2 border-brandBlack p-4 rounded-xl print:border-gray-400">
            <span className="font-mono text-[10px] font-black uppercase text-brandPink block mb-1">
              Primary Philosophical Concept: {story.keyConcept.title}
            </span>
            <blockquote className="font-bold text-base sm:text-lg italic text-brandBlack mb-1">
              "{story.keyConcept.quote}"
            </blockquote>
            <p className="text-xs sm:text-sm text-neutral-800 leading-relaxed">
              {story.keyConcept.explanation}
            </p>
          </div>

          {/* Synchronized Oral Folklore Recitation Table */}
          <div>
            <h3 className="font-mono text-xs font-black uppercase tracking-wider mb-2 text-brandBlack border-b border-brandBlack/40 pb-1">
              Transcribed Sentences &amp; Phonetic Alignment
            </h3>
            <div className="space-y-3 font-sans text-xs">
              {story.sentences.map((sent, idx) => (
                <div key={idx} className="bg-white border border-brandBlack/30 p-2.5 rounded-lg space-y-1">
                  <div className="flex items-center gap-2">
                    <span className="font-mono font-black text-brandPink bg-brandPink/10 px-1.5 py-0.5 rounded text-[10px]">
                      #{idx + 1}
                    </span>
                    <span className="font-bold text-brandBlack">{sent.en}</span>
                  </div>
                  <div className="pl-6 font-serif text-sm font-semibold text-neutral-900">
                    {sent.ml}
                  </div>
                  <div className="pl-6 font-mono text-[11px] text-neutral-500 italic">
                    [{sent.transliteration}]
                  </div>
                </div>
              ))}
            </div>
          </div>

          {/* Citation & Provenance Footer */}
          <div className="border-t-2 border-brandBlack pt-4 font-mono text-xs text-neutral-700 space-y-1">
            <div className="font-bold">Permanent Archival Citation:</div>
            <div className="bg-white p-2 rounded border border-brandBlack/30 text-[11px] select-all font-mono">
              KathaBridge Oral Heritage Registry ({currentDate.slice(0, 4)}). <em>{story.title}</em>. Verified by {story.scholarVerifier || "Kerala Folklore Society"}. Retrieved from https://kathabridge.vercel.app/story/{story.id}
            </div>
          </div>
        </div>

        {/* Action Toolbar - Hidden in print */}
        <div className="p-4 bg-brandYellow/20 border-t-4 border-brandBlack flex flex-wrap items-center justify-between gap-3 rounded-b-xl print:hidden">
          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="bg-brandPink hover:bg-brandPinkDark text-white px-4 py-2 rounded-xl font-mono text-xs font-black border-2 border-brandBlack shadow-[2px_2px_0px_#080808] flex items-center gap-1.5 transition cursor-pointer"
            >
              <span>🖨️</span>
              <span>Print / Save as PDF</span>
            </button>
            <button
              onClick={handleCopyMarkdown}
              className="bg-white hover:bg-neutral-100 text-brandBlack px-3.5 py-2 rounded-xl font-mono text-xs font-black border-2 border-brandBlack shadow-[2px_2px_0px_#080808] flex items-center gap-1.5 transition cursor-pointer"
            >
              <span>{copied ? "✅ Copied" : "📋 Copy Monograph"}</span>
            </button>
          </div>
          <button
            onClick={() => {
              Soundtrack.playModalPop();
              onClose();
            }}
            className="text-xs font-mono font-bold text-neutral-600 hover:text-brandBlack underline cursor-pointer"
          >
            Close Viewer
          </button>
        </div>
      </div>
    </div>
  );
};
